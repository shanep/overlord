import { describe, expect, it } from 'vitest';

import { digestTranscript, promptText } from './digest.js';
import {
  assistant,
  jsonl,
  sidechain,
  text,
  toolResult,
  toolUse,
  userPrompt,
} from './test-helpers/fixtures.js';

type Fields = Readonly<Record<string, unknown>>;

function digest(records: readonly Fields[], ...raw: string[]): ReturnType<typeof digestTranscript> {
  return digestTranscript([...jsonl(records).split('\n'), ...raw]);
}

function reply(uuid: string, content: readonly Fields[]): Fields {
  return assistant({ uuid, at: 0, messageId: uuid, content });
}

function result(uuid: string, toolUseId: string, output: string | readonly unknown[]): Fields {
  return toolResult(uuid, 0, [{ toolUseId, text: output }]);
}

describe('promptText', () => {
  it('keeps what the user typed and drops the reminders around it', () => {
    expect(promptText('  Fix the parser  ')).toBe('Fix the parser');
    expect(promptText('Fix it<system-reminder>\nnoise\n</system-reminder>')).toBe('Fix it');
    expect(promptText('<system-reminder>only noise</system-reminder>')).toBeNull();
  });

  it('drops what Claude Code wrote in the user turn', () => {
    for (const written of [
      '<task-notification>\n<status>completed</status>\n</task-notification>',
      '<local-command-stdout>Set model</local-command-stdout>',
      '<local-command-stderr>oops</local-command-stderr>',
      '<bash-stdout>ok</bash-stdout><bash-stderr></bash-stderr>',
      '<bash-stderr>bad</bash-stderr>',
      '[Request interrupted by user for tool use]',
      'Caveat: the messages below were generated by the user',
      'This session is being continued from a previous conversation.',
    ]) {
      expect(promptText(written)).toBeNull();
    }
  });

  it('turns slash commands and shell input back into what was typed', () => {
    expect(
      promptText(
        '<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>',
      ),
    ).toBe('/model');
    expect(
      promptText('<command-message>review</command-message>\n<command-name>/review</command-name>'),
    ).toBe('/review');
    expect(
      promptText('<command-name>/loop</command-name><command-args> 5m /check </command-args>'),
    ).toBe('/loop 5m /check');
    expect(promptText('<command-name> </command-name>')).toBeNull();
    expect(promptText('<command-name>/half typed')).toBeNull();
    expect(promptText('<bash-input> git status </bash-input>')).toBe('! git status');
  });
});

describe('digestTranscript', () => {
  it('collects the prompts of the main thread only', () => {
    const found = digest(
      [
        userPrompt('u1', 0, 'Group the fleet by project'),
        userPrompt('u2', 0, 'meta', { isMeta: true }),
        userPrompt('u3', 0, 'summary of before', { isCompactSummary: true }),
        sidechain('a1', userPrompt('u4', 0, 'subagent task')),
        userPrompt('u5', 0, '<task-notification>done</task-notification>'),
        userPrompt('u6', 0, '', {
          message: {
            role: 'user',
            content: [text('yes, build it'), text('<system-reminder>x</system-reminder>')],
          },
        }),
      ],
      'not json',
    );
    expect(found.prompts).toStrictEqual(['Group the fleet by project', 'yes, build it']);
  });

  it('prefers the /rename title over the generated one, and has none without either', () => {
    expect(digest([{ type: 'ai-title', aiTitle: 'Generated' }]).title).toBe('Generated');
    expect(
      digest([
        { type: 'custom-title', customTitle: 'Mine' },
        { type: 'ai-title', aiTitle: 'Generated' },
      ]).title,
    ).toBe('Mine');
    expect(digest([]).title).toBeNull();
  });

  it('lists files changed with the edit tools once each, in order', () => {
    const found = digest([
      reply('a1', [
        toolUse('t1', 'Edit', { file_path: '/r/b.ts' }),
        toolUse('t2', 'Write', { file_path: '/r/a.ts' }),
        toolUse('t3', 'Read', { file_path: '/r/read.ts' }),
        toolUse('t4', 'Edit', { file_path: '' }),
        toolUse('t5', 'Edit', null),
        toolUse('t6', 'MultiEdit', { path: '/r/wrong-field.ts' }),
        toolUse('t7', 'NotebookEdit', { file_path: 7 }),
      ]),
      reply('a2', [toolUse('t8', 'Edit', { file_path: '/r/b.ts' })]),
    ]);
    expect(found.files).toStrictEqual(['/r/b.ts', '/r/a.ts']);
  });

  it('reads commits and pushes from git output only', () => {
    const commitOutput = [
      'pre-commit hooks ok',
      '[master 1a2b3c4] Add the combine button',
      '[detached HEAD 5d6e7f8] Resolve the conflict',
      ' 3 files changed',
    ].join('\n');
    const pushOutput = 'To github.com:me/repo\n   1a2b3c4..5d6e7f8  HEAD -> master\n';
    const found = digest([
      reply('a1', [
        toolUse('git1', 'Bash', { command: 'git commit -m "x"' }),
        toolUse('git2', 'Bash', { command: 'git rebase --continue' }),
        toolUse('push', 'Bash', { command: 'git push origin HEAD:master' }),
        toolUse('grep', 'Bash', { command: 'grep -r "HEAD -> master" .' }),
        toolUse('log', 'Bash', { command: 'git log -5' }),
        toolUse('read', 'Read', { file_path: '/r/a.ts' }),
      ]),
      result('r1', 'git1', commitOutput),
      result('r2', 'git2', [{ type: 'text', text: '[master 1a2b3c4] Add the combine button' }]),
      result('r3', 'push', pushOutput),
      result('r4', 'grep', `[master 9999999] Not mine\n${pushOutput}`),
      result('r5', 'log', '   0000000..1111111  HEAD -> master'),
      result('r6', 'read', '[master 2222222] In a file'),
      result('r7', 'unknown', '[master 3333333] Unknown call'),
    ]);
    expect(found.commits).toStrictEqual([
      '1a2b3c4 Add the combine button',
      '5d6e7f8 Resolve the conflict',
    ]);
    expect(found.pushes).toStrictEqual(['1a2b3c4..5d6e7f8 HEAD -> master']);
  });

  it('keeps the last reply that had text', () => {
    const found = digest([
      reply('a1', [text('First answer')]),
      reply('a2', [text('Landed it.'), text('All checks pass.')]),
      reply('a3', [toolUse('t1', 'Bash', { command: 'ls' })]),
      sidechain('sub', reply('a4', [text('Subagent says hi')])),
    ]);
    expect(found.lastReply).toBe('Landed it.\nAll checks pass.');
    expect(digest([]).lastReply).toBeNull();
  });
});
